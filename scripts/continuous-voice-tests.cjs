const {chromium}=require('../frontend/node_modules/playwright');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const out=path.join(__dirname,'../verification');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true,args:['--autoplay-policy=no-user-gesture-required']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[],checks=[];page.setDefaultTimeout(20000);
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{
  window.testAudio=[];const AudioNative=window.Audio;
  window.Audio=class extends AudioNative{constructor(src){super(src);window.testAudio.push(this);}};
  window.sent=[];window.received=[];const WS=window.WebSocket;
  window.WebSocket=class extends WS{constructor(...args){super(...args);this.addEventListener('message',e=>window.received.push(JSON.parse(e.data)));}send(data){window.sent.push(JSON.parse(data));super.send(data);}};
  window.micRequests=0;window.micTracks=[];
  navigator.mediaDevices.getUserMedia=async()=>{
   window.micRequests++;window.micContext=new AudioContext();await window.micContext.resume();
   window.micDestination=window.micContext.createMediaStreamDestination();window.micTracks.push(...window.micDestination.stream.getTracks());
   window.speak=async()=>{const data=await fetch('/audio/hello.wav').then(r=>r.arrayBuffer());const buffer=await window.micContext.decodeAudioData(data);const source=window.micContext.createBufferSource();source.buffer=buffer;source.connect(window.micDestination);source.start(0,0,3);return 3;};
   return window.micDestination.stream;
  };
 });
 const check=name=>{checks.push(name);console.log('PASS',name)};
 await page.goto(process.env.APP_URL||'http://127.0.0.1:8080');await page.getByText('离线剧情 · MOCK').waitFor();
 await page.screenshot({path:out+'/desktop.png',fullPage:true});
 await page.getByRole('button',{name:'开始连续对话',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.mic')?.textContent==='结束对话',{},{timeout:60000});
 await page.evaluate(()=>window.speak());
 await page.waitForFunction(()=>window.received.some(m=>m.type==='transcript'),{},{timeout:30000});
 check('Local Silero detects Chinese speech and silence; sends first utterance automatically');
 await page.waitForFunction(()=>window.testAudio.some(a=>!a.paused&&a.currentTime>0.1));
 const old=await page.evaluate(()=>window.testAudio.length);
 const before=await page.evaluate(()=>({begins:window.sent.filter(m=>m.type==='begin'&&m.voice).length,transcripts:window.received.filter(m=>m.type==='transcript').length}));
 await page.evaluate(()=>window.speak());
 await page.waitForFunction(n=>window.sent.filter(m=>m.type==='begin'&&m.voice).length>n,before.begins);
 assert.equal(await page.evaluate(n=>window.testAudio.slice(0,n).every(a=>a.paused),old),true);
 check('Second utterance interrupts response without another click');
 await page.waitForFunction(n=>window.received.filter(m=>m.type==='transcript').length>n,before.transcripts,{timeout:30000});
 assert.equal(await page.evaluate(()=>window.micRequests),1);check('Two automatic voice turns share one microphone session');
 await page.getByRole('button',{name:'结束连续对话'}).click();
 assert.equal(await page.evaluate(()=>window.micTracks.every(t=>t.readyState==='ended')),true);
 assert.equal(await page.evaluate(()=>window.testAudio.every(a=>a.paused)),true);check('End conversation stops tracks and playback');
 await page.evaluate(()=>{window.originalMic=navigator.mediaDevices.getUserMedia;navigator.mediaDevices.getUserMedia=()=>new Promise(resolve=>window.resolveMic=resolve);});
 await page.getByRole('button',{name:'开始连续对话',exact:true}).click();await page.getByRole('button',{name:'结束连续对话'}).click();
 await page.evaluate(()=>{const ctx=new AudioContext();window.lateContext=ctx;window.lateStream=ctx.createMediaStreamDestination().stream;window.resolveMic(window.lateStream);});
 await page.waitForFunction(()=>window.lateStream.getTracks().every(t=>t.readyState==='ended'));
 check('Permission result arriving after stop is discarded and tracks released');
 await page.evaluate(()=>{navigator.mediaDevices.getUserMedia=window.originalMic;});
 await page.getByRole('button',{name:'开始连续对话',exact:true}).click();await page.waitForFunction(()=>document.querySelector('.mic')?.textContent==='结束对话',{},{timeout:60000});
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
 await page.getByRole('button',{name:'开始连续对话',exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>window.micTracks.every(t=>t.readyState==='ended')),true);check('Backgrounding page releases persistent microphone');
 await page.evaluate(()=>{delete document.hidden;});
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:out+'/mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);check('390px Mira mobile layout has no horizontal overflow');
 await page.evaluate(()=>{navigator.mediaDevices.getUserMedia=()=>Promise.reject(new DOMException('Denied','NotAllowedError'));});
 await page.getByRole('button',{name:'开始连续对话',exact:true}).click();await page.getByRole('alert').waitFor();
 await page.getByRole('button',{name:'你在等谁？',exact:true}).click();await page.locator('.mira.worried').waitFor();check('Permission denial retains working text conversation');
 assert.deepEqual(errors,[]);
 fs.writeFileSync(out+'/continuous-voice-tests.json',JSON.stringify({date:new Date().toISOString(),browser:'Chrome headless',microphone:'Web Audio injected Chinese WAV; real local Silero inference; not physical microphone',checks,errors},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
